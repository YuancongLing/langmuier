"""Independently decode strict LVDS HEX input and verify actual GUI CSV/LPD v3.

This standard-library reference uses a 40-bit integer for each five-byte
group, independently of Rust's byte-field decoder. It never repairs source
bytes, computes CRC, writes a capture, or labels generated bytes as supplied
data. Network wrappers, when created separately, are artificial envelopes.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import struct
import sys


CSV_COLUMNS = (
    'frame_index', 'frame_seconds', 'frame_microseconds', 'frame_seq_u8',
    'sample_index', 'sample_time_us', 'ch1_code10', 'ch2_code10',
    'ch1_adc16_reconstructed', 'ch2_adc16_reconstructed', 'integrity',
)
LPD_HEADER_FIELDS = (
    ('magic', b'LMPROBE\0'), ('version', 3), ('header_bytes', 40),
    ('endian_marker', 0x01020304), ('samples_per_channel', 100),
    ('sample_interval_us', 500), ('record_bytes', 409),
    ('representation', 1), ('flags', 3), ('channel_count', 2),
    ('sequence_bits', 8),
)


class VerificationError(ValueError):
    """A source field or stored value differs from the independent reference."""


def require_equal(actual, expected, context):
    if actual != expected:
        raise VerificationError(f'{context}: actual {actual!r}; expected {expected!r}')


def decode_frames(wires):
    """Validate fixed fields and return all decoded values without mutation.

    Generic input may contain device clock or sequence gaps. The optional
    supplied-baseline assertion checks the particular 20-frame continuity
    contract separately; gaps are not silently filled or reordered.
    """
    if not wires:
        raise VerificationError('HEX input is empty; expected at least one frame')
    frames = []
    for index, wire in enumerate(wires):
        context = f'HEX frame {index}'
        require_equal(len(wire), 269, f'{context} length')
        for actual, expected, field in [
            (wire[:2], b'\xEB\x90', 'header'),
            (wire[2], 0x55, 'SRC'), (wire[3], 0xAA, 'DST'),
            (wire[4:6], b'\x01\x07', 'LEN'),
            (wire[6], 0xAA, 'TYPE'), (wire[266], 0, 'DATA251 reserved'),
        ]:
            require_equal(actual, expected, f'{context} {field}')
        seconds, micros = struct.unpack_from('>II', wire, 7)
        if not 0 <= micros < 1000000:
            raise VerificationError(
                f'{context} microseconds: actual {micros}; expected 0..999999')
        channels = []
        for start in (15, 140):
            channel = []
            for offset in range(start, start + 125, 5):
                word = int.from_bytes(wire[offset:offset + 5], 'big')
                channel.extend((word >> shift) & 1023 for shift in (30, 20, 10, 0))
            channels.append(channel)
        base = seconds * 1000000 + micros
        frames.append({
            'frame_index': index,
            'frame_seconds': seconds,
            'frame_microseconds': micros,
            'frame_seq_u8': wire[265],
            'channel_1_code10': channels[0],
            'channel_2_code10': channels[1],
            'first_sample_time_us': base,
            'last_sample_time_us': base + 99 * 500,
            'wire_hex': wire.hex(),
        })
    return frames


def assert_supplied_baseline(frames):
    """Check only the explicit supplied 20-frame contract, never its provenance."""
    require_equal(len(frames), 20, 'baseline frame_count')
    for index, frame in enumerate(frames):
        for field, expected in [
            ('frame_seconds', 1700000000),
            ('frame_microseconds', index * 50000),
            ('frame_seq_u8', index),
        ]:
            require_equal(frame[field], expected, f'baseline frame {index} {field}')
        if index:
            require_equal(frame['first_sample_time_us'],
                          frames[index - 1]['last_sample_time_us'] + 500,
                          f'baseline frame {index} first_sample_time_us continuity')
    require_equal(frames[0]['channel_1_code10'][:4], [886, 805, 723, 642],
                  'baseline frame 0 channel 1 first four code10')
    require_equal(frames[0]['channel_2_code10'][:4], [846, 784, 721, 659],
                  'baseline frame 0 channel 2 first four code10')
    require_equal(frames[0]['channel_1_code10'][0] * 64 - 32768, 23936,
                  'baseline frame 0 channel 1 first ADC reconstructed')
    require_equal(frames[0]['channel_2_code10'][0] * 64 - 32768, 21376,
                  'baseline frame 0 channel 2 first ADC reconstructed')


def csv_rows(frames):
    for frame in frames:
        for sample in range(100):
            ch1 = frame['channel_1_code10'][sample]
            ch2 = frame['channel_2_code10'][sample]
            yield [
                frame['frame_index'], frame['frame_seconds'],
                frame['frame_microseconds'], frame['frame_seq_u8'], sample,
                frame['first_sample_time_us'] + sample * 500,
                ch1, ch2, ch1 * 64 - 32768, ch2 * 64 - 32768,
                'CRC_NOT_CHECKED',
            ]


def write_reference_csv(path, frames):
    """Create a new reference file exclusively; never replace existing data."""
    with Path(path).open('x', encoding='utf-8', newline='') as stream:
        writer = csv.writer(stream, lineterminator='\n')
        writer.writerow(CSV_COLUMNS)
        writer.writerows(csv_rows(frames))


def verify_csv(path, frames):
    """Read every stored CSV field and report the first exact mismatch."""
    with Path(path).open(encoding='utf-8', newline='') as stream:
        reader = csv.reader(stream)
        header = next(reader, None)
        require_equal(header, list(CSV_COLUMNS), 'CSV header')
        count = 0
        for count, expected in enumerate(csv_rows(frames), 1):
            frame_index, sample = divmod(count - 1, 100)
            context = f'CSV row {count + 1} frame {frame_index} sample {sample}'
            actual = next(reader, None)
            if actual is None:
                raise VerificationError(f'{context}: actual EOF; expected 11 columns')
            require_equal(len(actual), 11, f'{context} column_count')
            for name, value, wanted in zip(CSV_COLUMNS, actual, expected):
                require_equal(value, str(wanted), f'{context} column {name}')
        extra = next(reader, None)
        if extra is not None:
            raise VerificationError(
                f'CSV row {count + 2}: actual {extra!r}; expected EOF')
    return {'status': 'PASS', 'data_rows': count, 'columns_checked': count * 11}


def verify_lpd(path, frames):
    """Read the complete v3 header, records, and EOF without Rust helpers."""
    data = Path(path).read_bytes()
    if len(data) < 40:
        raise VerificationError(
            f'LPD header truncated: actual {len(data)} bytes; expected 40')
    header = struct.unpack_from('<8sHHIIIIIIHH', data)
    for actual, (name, expected) in zip(header, LPD_HEADER_FIELDS):
        require_equal(actual, expected, f'LPD header {name}')
    for index, frame in enumerate(frames):
        offset = 40 + index * 409
        available = max(0, len(data) - offset)
        if available < 409:
            raise VerificationError(
                f'LPD record {index} truncated: actual {available} bytes; expected 409')
        seconds, micros, sequence = struct.unpack_from('<IIB', data, offset)
        for name, actual in [('frame_seconds', seconds),
                             ('frame_microseconds', micros),
                             ('frame_seq_u8', sequence)]:
            require_equal(actual, frame[name], f'LPD record {index} {name}')
        for channel, start in [(1, 9), (2, 209)]:
            codes = struct.unpack_from('<100H', data, offset + start)
            expected = frame[f'channel_{channel}_code10']
            for sample, (actual, wanted) in enumerate(zip(codes, expected)):
                require_equal(actual, wanted,
                              f'LPD record {index} channel {channel} sample {sample} code10')
    require_equal(len(data), 40 + len(frames) * 409, 'LPD EOF file_bytes')
    return {'status': 'PASS', 'version': 3, 'file_bytes': len(data),
            'records': len(frames), 'codes_checked': len(frames) * 200}


def file_info(path):
    path = Path(path)
    data = path.read_bytes()
    return {'path': str(path.resolve()), 'bytes': len(data),
            'sha256': hashlib.sha256(data).hexdigest()}


def build_manifest(source, frames):
    return {
        'schema_version': 1,
        'source': {**file_info(source), 'label': 'original HEX input; UDP wrapper artificial'},
        'protocol': {'header_hex': 'eb9055aa0107aa', 'frame_bytes': 269,
                     'samples_per_channel': 100, 'sample_interval_us': 500,
                     'integrity': 'CRC_NOT_CHECKED'},
        'frame_count': len(frames),
        'sample_count_per_channel': len(frames) * 100,
        'frames': frames,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--txt', type=Path, required=True,
                        help='original, unmodified HEX source; one 269B frame per line')
    parser.add_argument('--reference-csv', type=Path,
                        help='exclusively create full independent 11-column reference')
    parser.add_argument('--manifest', type=Path,
                        help='exclusively create complete values and original-byte manifest')
    parser.add_argument('--csv', type=Path, help='verify actual native GUI science CSV')
    parser.add_argument('--lpd', type=Path, help='verify actual native GUI LPD v3')
    parser.add_argument('--assert-supplied-baseline', action='store_true',
                        help='also enforce the stated 20-frame time/seq/golden contract')
    args = parser.parse_args(argv)
    try:
        # Shared strict HEX ingestion, never shared scientific decoding.
        from lvds_txt_to_pcapng import read_hex_frames
        frames = decode_frames(read_hex_frames(args.txt))
        if args.assert_supplied_baseline:
            assert_supplied_baseline(frames)
        report = {'source': file_info(args.txt), 'frame_count': len(frames),
                  'sample_count_per_channel': len(frames) * 100,
                  'baseline_assertion': 'PASS' if args.assert_supplied_baseline else 'NOT_RUN',
                  'CRC': 'NOT_CHECKED',
                  'csv': None, 'lpd_v3': None}
        if args.csv:
            report['csv'] = {**file_info(args.csv), **verify_csv(args.csv, frames)}
        if args.lpd:
            report['lpd_v3'] = {**file_info(args.lpd), **verify_lpd(args.lpd, frames)}
        if args.reference_csv:
            write_reference_csv(args.reference_csv, frames)
            report['reference_csv'] = file_info(args.reference_csv)
        if args.manifest:
            manifest = build_manifest(args.txt, frames)
            with args.manifest.open('x', encoding='utf-8', newline='\n') as stream:
                json.dump(manifest, stream, ensure_ascii=False, indent=2)
                stream.write('\n')
            report['manifest'] = file_info(args.manifest)
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0
    except (OSError, ValueError, csv.Error) as error:
        print(f'FAIL: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
